//! The rustdoc header that makes `#[preview]` blocks interactive.

const STYLE: &str = include_str!("../assets/styleguide.css");
const SCRIPT: &str = include_str!("../assets/styleguide.js");

/// The `--html-in-header` file `render` writes to `styleguide/header.html`.
///
/// Point docs.rs at it from the documented crate's `Cargo.toml`:
///
/// ```toml
/// [package.metadata.docs.rs]
/// rustdoc-args = ["--html-in-header", "styleguide/header.html"]
/// ```
///
/// docs.rs serves rustdoc pages without a Content-Security-Policy, so the
/// inline script and the playground iframe run there as they do locally.
pub fn header() -> String {
    format!(
        "<!-- generated by gpui-styleguidist; do not edit -->\n<style>\n{STYLE}</style>\n<script>\n{SCRIPT}</script>\n"
    )
}
